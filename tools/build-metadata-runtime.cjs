/* Run after changing the parser, worker, vendor library or teaching PNG.
 * The committed browser bundle works without fetch/importScripts, including
 * when a reader opens index.html directly from the filesystem.
 */
const fs = require('fs'), path = require('path');
const root = path.resolve(__dirname, '..');
const inputs = ['assets/js/vendor/exifr-7.1.3.umd.js', 'assets/js/reverse-metadata-core.js', 'assets/js/reverse-metadata-worker.js'];
const source = inputs.map(file => fs.readFileSync(path.join(root, file), 'utf8')).join('\n;\n');
const sample = fs.readFileSync(path.join(root, 'assets/practice/reverse-sample.png')).toString('base64');
const version = Number(source.match(/var VERSION = (\d+)/)[1]);
const result = '/* Generated by tools/build-metadata-runtime.cjs. Includes exifr 7.1.3 (MIT); see vendor/exifr-LICENSE.txt. Do not edit. */\n' +
  'window.REVERSE_METADATA_RUNTIME = ' + JSON.stringify({ version: version, workerSource: source, sampleBase64: sample }) + ';\n';
const target = path.join(root, 'assets/js/reverse-metadata-runtime.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== result) { console.error('Metadata bundle is stale. Run node tools/build-metadata-runtime.cjs'); process.exitCode = 1; }
  else console.log('PASS self-contained metadata bundle matches sources and sample');
} else { fs.writeFileSync(target, result); console.log('Wrote self-contained metadata bundle: ' + Buffer.byteLength(result) + ' bytes'); }
